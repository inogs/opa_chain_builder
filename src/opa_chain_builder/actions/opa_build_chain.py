LOGGER = logging.getLogger(__name__)

CONDA_LOCK_FILE_NAME = "environment.lock"
LOCK_PLATFORM_PREFIX = "# platform:"

# Wrapper that runs the AWS CLI of its own micromamba environment without
# activating it. The "-I" flag runs Python in isolated mode, ignoring the
# PYTHON* environment variables and the user site-packages directory, so
# that the Python environment of the chain cannot interfere with it.
AWS_WRAPPER_TEMPLATE = """#!/bin/sh
# Generated by opa-chain-builder: runs the AWS CLI installed in {env_prefix}
exec {python_exe} -I {aws_exe} "$@"
"""


REPOS = MappingProxyType(
    {
        "model_builder": "git@github.com:inogs/ModelBuild.git",
        "bit.sea": "git@github.com:inogs/bit.sea.git",
        "ogstm_preproc": "git@github.com:inogs/ogstm_preproc.git",
        "ogstm_postproc": "git@github.com:inogs/ogstm_postproc.git",
    }
)


@dataclass(frozen=True)
class BuildChainOptions:
    """
    Options that control which steps of the chain build are executed.

    Attributes:
        skip_clone_chain: If ``True``, the chain repository is assumed to be
            already cloned inside the chain home and it is not cloned again.
        skip_python_env: If ``True``, the Python (micromamba) environment is
            not created.
        skip_spack_env: If ``True``, the Spack environment is not created.
        skip_download_repos: If ``True``, the auxiliary repositories listed
            in ``REPOS`` are not cloned.
        skip_aws: If ``True``, the AWS CLI (and its micromamba environment)
            is not installed.

    Raises:
        ValueError: If ``skip_python_env`` is ``True`` but ``skip_spack_env``
            is ``False``, because the Spack environment requires the Python
            environment to be built.

    """

    skip_clone_chain: bool = False
    skip_python_env: bool = False
    skip_spack_env: bool = False
    skip_download_repos: bool = False
    skip_aws: bool = False

    def __post_init__(self) -> None:
        """Check that the combination of options is consistent."""
        if self.skip_python_env and not self.skip_spack_env:
            error_msg = (
                "The Spack environment requires the Python environment: "
                "skip_python_env can be enabled only if skip_spack_env is "
                "enabled too"
            )
            raise ValueError(error_msg)


FINAL_MESSAGE = """
Well done! Your chain is ready (almost)!

The next steps:
1. Execute `source {env_file}` to activate your environment.
2. Execute `spack -e {spack_env_dir} install` to install all chain requirements
3. Install bit.sea: `pip install -e {chain_home}/HOST/{chain_hostname}/bit.sea`
4. Execute the model builder in {chain_home}/HOST/{chain_hostname}
5. Run `make` and `make install` inside the {chain_home}/bin/src directory

And that's it! Enjoy :-D
"""


def _read_lock_platform(lock_file: Path) -> str | None:
    """
    Read the platform declared in an explicit conda lock file.

    Explicit lock files (generated with ``conda list --explicit`` or
    ``micromamba env export --explicit``) contain a header line like
    ``# platform: linux-64``.

    Args:
        lock_file: Path to the lock file.

    Returns:
        The declared platform, or ``None`` if the file does not declare one.

    """
    with lock_file.open() as f:
        for raw_line in f:
            line = raw_line.strip()
            if line.startswith(LOCK_PLATFORM_PREFIX):
                return line.removeprefix(LOCK_PLATFORM_PREFIX).strip()
            if line and not line.startswith("#"):
                # The header is over
                break
    return None


def _get_usable_lock_file(python_config_dir: Path) -> Path | None:
    """
    Return the conda lock file to use, if any.

    The lock file is used only if it exists and it has been generated for
    the platform of the current machine (or if it does not declare any
    platform).

    Args:
        python_config_dir: Directory containing the conda environment files.

    Returns:
        The path of the lock file, or ``None`` if no usable lock file exists.

    """
    lock_file = python_config_dir / CONDA_LOCK_FILE_NAME
    if not lock_file.is_file():
        LOGGER.debug("No conda lock file found at %s", lock_file)
        return None

    lock_platform = _read_lock_platform(lock_file)
    current_platform = micromamba_platform()
    if lock_platform is not None and lock_platform != current_platform:
        LOGGER.warning(
            "The conda lock file %s has been generated for platform %s, "
            "but the current platform is %s; it will be ignored",
            lock_file,
            lock_platform,
            current_platform,
        )
        return None

    return lock_file


def _build_py_env(
    python_config_dir: Path, env_prefix: Path, opa_name: str
) -> None:
    micromamba_exe = MicromambaExec.from_current_env()

    lock_file = _get_usable_lock_file(python_config_dir)
    if lock_file is not None:
        LOGGER.info("Building Python environment from lock file %s", lock_file)
        micromamba_exe.create_env(env_file=lock_file, prefix=env_prefix)
    else:
        env_file = python_config_dir / "environment.yaml"
        LOGGER.info("Building Python environment from %s", env_file)
        with tempfile.TemporaryDirectory() as temporary_dir:
            temp_dir_path = Path(temporary_dir)
            temp_env_file = temp_dir_path / "environment.yaml"

            env_file_content = env_file.read_text()
            env_file_content = env_file_content.replace("<OPA_NAME>", opa_name)
            temp_env_file.write_text(env_file_content)
            micromamba_exe.create_env(
                env_file=temp_env_file, prefix=env_prefix
            )

    pip_packages = python_config_dir / "pip_packages.txt"
    if not pip_packages.exists():
        LOGGER.debug("No pip packages file found at %s", pip_packages)
        LOGGER.info("Python environment setup complete at %s", env_prefix)
        return

    LOGGER.info("Installing pip packages from %s", pip_packages)
    pip_packages_content = pip_packages.read_text().splitlines()
    for raw_line in pip_packages_content:
        # Remove comments and whitespace
        pip_package = raw_line.split("#", 1)[0].strip()
        if len(pip_package) == 0:
            continue
        LOGGER.info("Installing pip package: %s", pip_package)
        commands = ["pip", "install", *pip_package.split()]
        micromamba_exe.run(commands=commands, env_prefix=env_prefix)
    LOGGER.info("Python environment setup complete at %s", env_prefix)


def _install_aws(
    aws_config_dir: Path, env_prefix: Path, tools_dir: Path
) -> None:
    """
    Install the AWS CLI in a dedicated micromamba environment.

    The AWS CLI cannot be installed in the Spack environment (the build
    fails) nor in the main Python environment (the environment cannot be
    solved), so it gets its own micromamba environment. A wrapper script
    named ``aws`` is then written inside ``tools_dir``: it runs the AWS CLI
    without the need of activating its environment.

    Args:
        aws_config_dir: Directory containing the ``environment.yaml`` file
            (and, optionally, the ``environment.lock`` file) of the AWS CLI
            environment.
        env_prefix: Prefix of the micromamba environment to create.
        tools_dir: Directory where the ``aws`` wrapper script is written;
            it is created if it does not exist.

    Raises:
        FileNotFoundError: If the ``aws`` executable or the Python
            interpreter are not found inside the new environment.

    """
    micromamba_exe = MicromambaExec.from_current_env()

    env_file = _get_usable_lock_file(aws_config_dir)
    if env_file is None:
        env_file = aws_config_dir / "environment.yaml"
    LOGGER.info("Building the AWS CLI environment from %s", env_file)
    micromamba_exe.create_env(env_file=env_file, prefix=env_prefix)

    # Resolve only the prefix: bin/python is a symlink to a versioned
    # interpreter (e.g. python3.14) and it must stay version agnostic
    env_bin_dir = env_prefix.resolve() / "bin"
    python_exe = env_bin_dir / "python"
    aws_exe = env_bin_dir / "aws"
    for exe in (python_exe, aws_exe):
        if not exe.is_file():
            error_msg = (
                f"File {exe} not found inside the AWS CLI environment "
                f"{env_prefix}"
            )
            raise FileNotFoundError(error_msg)

    tools_dir.mkdir(parents=True, exist_ok=True)
    wrapper = tools_dir / "aws"
    LOGGER.info("Writing the AWS CLI wrapper to %s", wrapper)
    wrapper.write_text(
        AWS_WRAPPER_TEMPLATE.format(
            env_prefix=env_bin_dir.parent,
            python_exe=shlex.quote(str(python_exe)),
            aws_exe=shlex.quote(str(aws_exe)),
        )
    )
    wrapper.chmod(0o755)
    LOGGER.info("AWS CLI setup complete")


def _build_spack_env(
    env_configs_dir: Path,
    spack_main_dir: Path,
    spack_env_dir: Path,
    chain_compiler: str,
    conda_env_path: Path | None = None,
) -> None:
    spack_config_dir = (env_configs_dir / "spack") / chain_compiler
    spack_bootstrap_dir = spack_config_dir / "bootstrap"
    if spack_bootstrap_dir.exists():
        LOGGER.debug(
            "Reading bootstrap directory from %s", spack_bootstrap_dir
        )
        bootstrap = Bootstrap.from_dir(spack_bootstrap_dir)
        bootstrap.execute(
            env_config_dir=spack_env_dir / "bootstrap",
            new_env_path=spack_env_dir,
            spack_main_dir=spack_main_dir,
        )
    else:
        LOGGER.debug("No bootstrap directory found in %s", spack_bootstrap_dir)

    replace_values = None
    if conda_env_path is not None:
        replace_values = {"CONDA_ENV_PATH": str(conda_env_path)}

    create_spack_env_from_yaml(
        spack_dir=spack_main_dir,
        env_dir=spack_env_dir,
        spack_yaml=spack_config_dir / "spack.yaml",
        allow_non_empty_path=True,
        replace_values=replace_values,
        concretized=False,
    )

    spack_exe = spack_main_dir / "bin" / "spack"

    if conda_env_path is not None:
        LOGGER.info("Setting up Python as external in Spack environment")
        execute_spack_command(
            spack_exe=spack_exe,
            args=["external", "find", "--path", str(conda_env_path), "python"],
            spack_env_dir=spack_env_dir,
        )

    LOGGER.info("Concretizing spack environment at %s", spack_env_dir)
    execute_spack_command(
        spack_exe=spack_exe,
        args=["concretize"],
        spack_env_dir=spack_env_dir,
    )
    LOGGER.info("Spack environment created at %s", spack_env_dir)

    LOGGER.info("Spack environment setup complete at %s", spack_env_dir)


def _write_chain_env_file(
    env_file: Path,
    chain_config: ChainConfig,
    spack_main_dir: Path,
    python_env_dir: Path,
    tools_dir: Path,
) -> None:
    chain_name = cast("str", chain_config.name)
    LOGGER.info("Writing chain config file to %s", env_file)
    # Refuse to be sourced in a shell where another chain is already loaded
    env_file_header = (
        f'if [ -n "${{OPA_NAME+x}}" ] && [ "$OPA_NAME" != "{chain_name}" ]; '
        "then\n"
        f'    echo "Error: OPA_NAME is already set to \\"$OPA_NAME\\" '
        f'(expected \\"{chain_name}\\")" >&2\n'
        "    return 1\n"
        "fi\n"
        f'export OPA_NAME="{chain_name}"\n\n'
    )
    spack_setup_file = spack_main_dir.resolve() / "share/spack/setup-env.sh"
    env_file_header += (
        "if ! command -v spack > /dev/null 2>&1; then\n"
        f'    source "{spack_setup_file}"\n'
        "fi\n\n"
    )
    # Add the tools of the chain (e.g. the AWS CLI wrapper) to the PATH,
    # avoiding duplicates if the file is sourced more than once
    tools_path = tools_dir.resolve()
    env_file_header += (
        f'case ":$PATH:" in\n'
        f'    *":{tools_path}:"*) ;;\n'
        f'    *) export PATH="{tools_path}:$PATH" ;;\n'
        "esac\n\n"
    )
    micromamba_exe = MicromambaExec.from_current_env()
    # Keep the micromamba shell function of the user, if already initialized
    # Show the chain name in the prompt instead of the full env prefix; the
    # value is parsed as YAML, so it is quoted to keep the trailing space
    env_file_footer = (
        "\nif ! declare -F micromamba > /dev/null; then\n"
        f'    eval "$("{micromamba_exe.exe_path.resolve()}" '
        'shell hook --shell bash)"\n'
        "fi\n"
        f"MAMBA_ENV_PROMPT='\"({chain_name}) \"' "
        f'micromamba activate "{python_env_dir.resolve()}"\n'
    )
    env_file.write_text(
        env_file_header
        + chain_config.prepare_environment_file()
        + env_file_footer
    )


def _clone_chain_repo(chain_config: ChainConfig, chain_home: Path) -> None:
    """
    Clone the chain repository into ``chain_home`` and fix key permissions.

    Args:
        chain_config: Concretized configuration of the chain to build.
        chain_home: Directory where the chain repository is cloned.

    """
    LOGGER.info("Cloning chain repository")
    clone_repository(
        repo_url="git@gitlab-ssh.hpc.cineca.it:OGS/v5c.git",
        destination=chain_home,
        ref=chain_config.branches.chain,
    )

    # We need to set the right permissions on the keys file of the repo
    key_dir = chain_home / "etc" / "sftp-config"
    LOGGER.debug("Setting permissions on files of directory %s", key_dir)
    for key in key_dir.iterdir():
        if not key.is_file():
            continue
        if key.name.startswith("."):
            continue
        LOGGER.debug("Setting permissions on file %s", key)
        key.chmod(0o600)


def _setup_chain_repo(
    chain_config: ChainConfig, chain_home: Path, *, skip_clone: bool
) -> None:
    """
    Clone the chain repository, or check that it is already there.

    Args:
        chain_config: Concretized configuration of the chain to build.
        chain_home: Directory where the chain repository is cloned.
        skip_clone: If ``True``, the repository is not cloned and it is
            assumed to be already inside ``chain_home``.

    Raises:
        RuntimeError: If git-lfs is not installed and the repository has to
            be cloned.
        FileNotFoundError: If the repository is not cloned but
            ``chain_home`` does not exist.

    """
    if skip_clone:
        LOGGER.info("Skipping the cloning of the chain repository...")
        if not chain_home.exists():
            error_msg = (
                "The chain repository will not be cloned, but the chain "
                f"home directory {chain_home} does not exist"
            )
            raise FileNotFoundError(error_msg)
        return

    if not is_git_lfs_installed():
        error_msg = (
            "git-lfs is not installed. Please install git-lfs to proceed."
        )
        raise RuntimeError(error_msg)

    _clone_chain_repo(chain_config=chain_config, chain_home=chain_home)


def _clone_auxiliary_repos(
    chain_config: ChainConfig, current_host_dir: Path
) -> None:
    """
    Clone the repositories listed in ``REPOS`` into ``current_host_dir``.

    Args:
        chain_config: Concretized configuration of the chain to build; it
            provides the branch to check out for each repository.
        current_host_dir: Directory of the current host inside the chain.

    """
    LOGGER.info("Cloning repos...")
    for repo_name, repo_url in REPOS.items():
        repo_branch_attribute = repo_name.split("_")[-1].replace(".", "")
        repo_branch = getattr(chain_config.branches, repo_branch_attribute)
        LOGGER.info(
            "Cloning repo %s using branch %s from %s",
            repo_name,
            repo_branch,
            repo_url,
        )

        clone_repository(
            repo_url=repo_url,
            destination=current_host_dir / repo_name,
            ref=repo_branch,
        )


def _prepare_env_dir(
    env_dir: Path, env_label: str, *, must_be_empty: bool
) -> None:
    """
    Create the directory of an environment, if it does not exist yet.

    Args:
        env_dir: Directory of the environment.
        env_label: Name of the environment, used in the error message.
        must_be_empty: If ``True``, the directory must be empty because the
            environment is going to be created inside it.

    Raises:
        OSError: If ``must_be_empty`` is ``True`` and the directory is not
            empty.

    """
    env_dir.mkdir(parents=True, exist_ok=True)
    if must_be_empty and any(env_dir.iterdir()):
        error_msg = (
            f"The directory of the {env_label} environment {env_dir} "
            "is not empty."
        )
        raise OSError(error_msg)


def build_chain(
    chain_config: ChainConfig,
    spack_main_dir: Path,
    env_configs_dir: Path,
    options: BuildChainOptions | None = None,
) -> None:
    """
    Build an OPA chain described by ``chain_config``.

    The chain repository is cloned into the chain home, the chain
    environment file is written, and the Python (micromamba) and Spack
    environments of the current host are created inside it. The AWS CLI
    is installed in its own micromamba environment and exposed through a
    wrapper in the ``tools`` directory of the current host.

    Args:
        chain_config: Concretized configuration of the chain to build.
        spack_main_dir: Directory of the Spack installation used to create
            the Spack environment.
        env_configs_dir: Directory containing the ``conda``, ``spack`` and
            ``aws`` environment configurations.
        options: Options that control which steps of the build are
            executed. If ``None``, the default options are used.

    Raises:
        ValueError: If ``chain_config`` has not been concretized.
        RuntimeError: If git-lfs is not installed and the chain repository
            has to be cloned.
        FileNotFoundError: If the chain repository is not cloned but the
            chain home directory does not exist.
        OSError: If the environment directories that have to be created
            are not empty.

    """
    if options is None:
        options = BuildChainOptions()

    chain_name = cast("str", chain_config.name)
    chain_home = chain_config.home
    chain_hostname = chain_config.hostname
    chain_compiler = chain_config.compiler
    if chain_home is None or chain_hostname is None:
        error_msg = (
            "This procedure has been called without concretizing the "
            "configuration first"
        )
        raise ValueError(error_msg)

    _setup_chain_repo(
        chain_config=chain_config,
        chain_home=chain_home,
        skip_clone=options.skip_clone_chain,
    )

    host_dir = chain_home / "HOST"
    current_host_dir = host_dir / chain_hostname
    spack_env_dir = current_host_dir / "spack_env"
    python_env_dir = current_host_dir / "python_env"
    aws_env_dir = current_host_dir / "aws"
    tools_dir = current_host_dir / "tools"

    env_file = chain_home / "chain_env.sh"
    _write_chain_env_file(
        env_file=env_file,
        chain_config=chain_config,
        spack_main_dir=spack_main_dir,
        python_env_dir=python_env_dir,
        tools_dir=tools_dir,
    )

    _prepare_env_dir(
        env_dir=spack_env_dir,
        env_label="spack",
        must_be_empty=not options.skip_spack_env,
    )
    _prepare_env_dir(
        env_dir=python_env_dir,
        env_label="python",
        must_be_empty=not options.skip_python_env,
    )
    _prepare_env_dir(
        env_dir=aws_env_dir,
        env_label="aws",
        must_be_empty=not options.skip_aws,
    )

    if options.skip_python_env:
        LOGGER.info("Skipping the creation of the Python environment...")
    else:
        python_config_dir = env_configs_dir / "conda"
        _build_py_env(
            python_config_dir=python_config_dir,
            env_prefix=python_env_dir,
            opa_name=chain_name,
        )

    if options.skip_spack_env:
        LOGGER.info("Skipping the creation of the Spack environment...")
    else:
        _build_spack_env(
            env_configs_dir=env_configs_dir,
            spack_main_dir=spack_main_dir,
            spack_env_dir=spack_env_dir,
            chain_compiler=chain_compiler,
            conda_env_path=python_env_dir,
        )

    if options.skip_aws:
        LOGGER.info("Skipping the installation of the AWS CLI...")
    else:
        _install_aws(
            aws_config_dir=env_configs_dir / "aws",
            env_prefix=aws_env_dir,
            tools_dir=tools_dir,
        )

    if options.skip_download_repos:
        LOGGER.info("Skipping the cloning of the auxiliary repositories...")
    else:
        _clone_auxiliary_repos(
            chain_config=chain_config, current_host_dir=current_host_dir
        )

    LOGGER.info("Chain is ready!")

    final_message = FINAL_MESSAGE.format(
        env_file=env_file,
        spack_env_dir=spack_env_dir.resolve(),
        chain_home=chain_home.resolve(),
        chain_hostname=chain_hostname,
    )
    print(final_message)  # noqa: T201
